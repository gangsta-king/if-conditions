m = int(input())
n = int(input())
x = int(input())
y = int(input())

# Проверяем и выводим соседа сверху (если он есть в таблице)
if x > 1:
    print(x - 1, y)

# Проверяем и выводим соседа слева (если он есть)
if y > 1:
    print(x, y - 1)

# Проверяем и выводим соседа снизу (если он есть)
if x < m:
    print(x + 1, y)

# Проверяем и выводим соседа справа (если он есть)
if y < n:
    print(x, y + 1)