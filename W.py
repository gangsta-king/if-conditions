n = int(input())

min_cost = 999999  # Заведомо огромное число для старта
ans_1, ans_10, ans_60 = 0, 0, 0

# Перебираем все возможные количества больших билетов
for c60 in range(n // 60 + 2):
    for c10 in range(n // 10 + 2):
        
        # Сколько поездок дают эти билеты
        total_rides = c60 * 60 + c10 * 10
        
        # Если поездок не хватило до n, докупаем оставшиеся по 1 штуке
        if total_rides >= n:
            c1 = 0
        else:
            c1 = n - total_rides
            
        # Считаем общую стоимость этого варианта
        cost = c60 * 440 + c10 * 125 + c1 * 15
        
        # Если этот вариант дешевле предыдущего — запоминаем его
        if cost < min_cost:
            min_cost = cost
            ans_1 = c1
            ans_10 = c10
            ans_60 = c60

# Выводим ответ (количество билетов на 1, на 10, на 60)
print(ans_1, ans_10, ans_60)